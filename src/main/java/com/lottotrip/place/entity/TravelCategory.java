package com.lottotrip.place.entity;

import lombok.AllArgsConstructor;
import lombok.Getter;

/**
 * 장소 분류. **TourAPI의 중분류(`cat2`)를 그대로 옮긴 것이다.** (roadmap 6-15, 결정 16)
 *
 * ## 왜 TourAPI 체계를 그대로 쓰나
 * 처음에는 우리가 정의한 8종(자연·해변·문화시설…)이었다. 그런데 회의에서 **여행 스타일 6종**
 * (휴식·맛집·감상·체험·활동·탐험)으로 후보를 거르기로 하면서 문제가 드러났다 —
 * **체험·활동·탐험이 전부 `LEISURE` 하나로 뭉쳐** 서로 다른 스타일이 같은 후보를 준다.
 *
 * `cat2`에는 **"휴양관광지"·"체험관광지"가 이름 그대로 있다.** 우리가 새로 나눌 이유가 없다.
 * 게다가 `cat2`는 **목록 응답에 함께 오므로**(강릉 30km 880건 중 빈 값 0건)
 * 스타일 필터에 추가 API 호출이 들지 않는다.
 *
 * ## ⚠️ 잃은 것 — `해변`·`카페`
 * 둘 다 `cat3`(`A01011200`·`A05020900`)라 `cat2`로 올리면 묻힌다.
 * 해수욕장은 {@link #NATURE_ATTRACTION}(자연관광지), 카페는 {@link #RESTAURANT}(음식점)으로 나간다.
 * **ERD 4-3 응답 예시가 `"category": "해변"`이라 프론트와 맞춰야 한다.**
 * 다시 필요해지면 `cat3`를 보는 규칙을 매퍼에 더하면 된다.
 *
 * `displayName`을 따로 두는 이유: DB에는 `RESTAURANT`로 저장하지만 API 응답에는
 * `"음식점"`으로 내려가야 한다. **표시명은 TourAPI가 쓰는 이름을 그대로 따른다** —
 * 우리가 지어내면 TourAPI 문서와 대조할 때 매번 번역해야 한다.
 *
 * 상수명을 `A0203`이 아니라 **의미명**으로 지은 이유: 결정 6으로 **상수명이 그대로
 * DB에 저장**되는데, `A0203`만 보고는 체험관광지인지 알 수 없다. 코드는 필드로 함께 든다.
 */
@Getter
@AllArgsConstructor
public enum TravelCategory {

    // ---------- A01 자연 ----------
    /** 산·해수욕장·계곡·폭포 등. **해수욕장이 여기 묻힌다**(예전 `BEACH`). */
    NATURE_ATTRACTION("A0101", "자연관광지"),
    NATURE_RESOURCE("A0102", "관광자원"),

    // ---------- A02 인문(문화/예술/역사) ----------
    HISTORY("A0201", "역사관광지"),
    /** **여행 스타일 "휴식형"이 직접 대응한다.** */
    RELAXATION("A0202", "휴양관광지"),
    /** **여행 스타일 "체험형"이 직접 대응한다.** */
    EXPERIENCE("A0203", "체험관광지"),
    INDUSTRY("A0204", "산업관광지"),
    ARCHITECTURE("A0205", "건축/조형물"),
    CULTURE_FACILITY("A0206", "문화시설"),
    FESTIVAL("A0207", "축제"),
    PERFORMANCE("A0208", "공연/행사"),

    // ---------- A03 레포츠 ("활동형") ----------
    SPORTS_INFO("A0301", "레포츠소개"),
    LAND_SPORTS("A0302", "육상 레포츠"),
    WATER_SPORTS("A0303", "수상 레포츠"),
    AIR_SPORTS("A0304", "항공 레포츠"),
    MIXED_SPORTS("A0305", "복합 레포츠"),

    // ---------- A04 쇼핑 / A05 음식 / B02 숙박 ----------
    SHOPPING("A0401", "쇼핑"),
    /** 카페도 여기 묻힌다(예전 `CAFE`). `cat3=A05020900`이 카페다. */
    RESTAURANT("A0502", "음식점"),
    /** ⚠️ 숙소는 사용자에게 따로 입력받으므로 **여행지 후보에서 뺄지 검토가 필요하다.** */
    LODGING("B0201", "숙박시설"),

    // ---------- C01 추천코스 ----------
    // 장소 하나가 아니라 묶음이라 성격이 다르다. 강원 전체에 10건뿐이다.
    FAMILY_COURSE("C0112", "가족코스"),
    SOLO_COURSE("C0113", "나홀로코스"),
    HEALING_COURSE("C0114", "힐링코스"),
    WALKING_COURSE("C0115", "도보코스"),
    CAMPING_COURSE("C0116", "캠핑코스"),
    FOOD_COURSE("C0117", "맛코스"),

    /**
     * 어느 `cat2`에도 걸리지 않았을 때.
     *
     * `places.category`는 NOT NULL이라 값이 반드시 있어야 한다. 예전 기본값은
     * `NATURE`였는데, 그러면 **모르는 것이 조용히 "자연"으로 둔갑**한다.
     * 별도 값으로 두면 "TourAPI가 새 분류를 추가했다"를 나중에 조회 한 번으로 찾아낼 수 있다.
     *
     * 실측(2026-08-15) 기준 강릉 30km 880건 중 `cat2`가 빈 것은 0건이라 거의 쓰이지 않아야 한다.
     * **이 값이 늘어난다면 그 자체가 신호다.**
     */
    UNKNOWN("", "분류 없음");

    /** TourAPI 중분류 코드. 응답의 `cat2`와 그대로 대조된다. */
    private final String cat2Code;

    private final String displayName;
}
