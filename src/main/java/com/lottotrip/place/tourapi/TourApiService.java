package com.lottotrip.place.tourapi;

/**
 * 어느 공공데이터 서비스를 부를 것인가. (roadmap 6-9, 결정 12)
 *
 * 이 프로젝트는 한국관광공사 API를 **두 가지** 쓴다. 둘은 **오퍼레이션명과 파라미터가 완전히 같고
 * 호스트만 다르다**(2026-08-15 실측). 그래서 조회 메서드를 종류별로 새로 만드는 대신,
 * "어느 쪽에 물어볼 것인가"만 골라 넘긴다.
 *
 * **왜 boolean이 아니라 enum인가.** `fetchLocationBasedList(..., true)`는 호출부만 봐서는
 * 그 `true`가 무엇을 뜻하는지 알 수 없다. `TourApiService.ACCESSIBLE`은 그 자리에서 읽힌다.
 * 나중에 서비스가 하나 더 늘어도 인자를 또 추가하지 않아도 된다.
 *
 * ⚠️ **일일 할당량은 서비스·오퍼레이션마다 따로 계산된다**(2026-08-15 실측).
 * 즉 무장애 조회는 국문 관광정보의 예산을 깎지 않는다.
 */
public enum TourApiService {

    /** 국문 관광정보(`KorService2`). 장소 조회의 기본값이다. */
    KOREAN,

    /**
     * 무장애 여행 정보(`KorWithService2`).
     *
     * 여기 담긴 장소는 국문 관광정보의 **부분집합**이다 — 무장애 정보가 등록된 것만 들어 있다
     * (강릉 20km 기준 763건 중 597건). 그래서 이 서비스로 조회하는 것 자체가
     * **"무장애 정보가 있는 장소만"이라는 필터** 역할을 한다.
     *
     * ⚠️ 다만 거기까지다. 등록된 내용은 전부 서술형 문장(`exit: "경사로 있음"`)이라
     * **"휠체어로 갈 수 있는가"를 기계적으로 판정할 수는 없다.**
     */
    ACCESSIBLE
}
